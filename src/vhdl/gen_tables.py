#!/usr/bin/env python3
"""Generate ssnail_tables_pkg.vhdl: the SiLU, GELU, exp and softplus tables and the
IQ2 / IQ3 codebooks, from the SSNAIL tools' ssnail_hw.py, so the hardware
uses exactly the emulator's coefficients and grids.  The output is a
synthesis source: commit it.

    python3 gen_tables.py [--check]       (--check: exit 1 if out of date)
"""
import os
import sys
_here = os.path.dirname(os.path.abspath(__file__))
_tools = os.environ.get("SSNAIL_TOOLS")
if not _tools:
    for _c in (os.path.join(_here, "SSNAIL"), os.path.join(_here, "SSNAIL", "ssnail_tools")):
        if os.path.exists(os.path.join(_c, "ssnail_isa.py")):
            _tools = _c
            break
sys.path.insert(0, _tools or os.path.join(_here, "SSNAIL"))
import numpy as np
import ssnail_hw as H

OUT = os.path.join(os.getcwd(), "ssnail_tables_pkg.vhdl")


def bits(v):
    return int(np.asarray(v, dtype=np.float32).view(np.uint32))


def table(name, t):
    out = [f"  -- {name}: [{float(t.lo)}, {float(t.hi)}), y = c0[i] + c1[i] * x\n",
           f"  constant {name}_LO : unsigned(31 downto 0) := x\"{bits(t.lo):08X}\";\n",
           f"  constant {name}_HI : unsigned(31 downto 0) := x\"{bits(t.hi):08X}\";\n",
           f"  constant {name}_K  : unsigned(31 downto 0) := x\"{bits(t.k):08X}\";\n"]
    for c, arr in (("C0", t.c0), ("C1", t.c1)):
        out.append(f"  constant {name}_{c} : tab_t := (\n")
        out.append(",\n".join(f"    x\"{bits(v):08X}\"" for v in arr))
        out.append(");\n")
    return "".join(out)


# IQ2 / IQ3 codebooks as small codes (a value per 2 or 3 bits, value 0 in
# the low bits): IQ2 codes 0, 1, 2 are 8, 25, 43; IQ3_XXS code k is
# IQ3_XXS_VALUES[k]; IQ3_S code k is 2k + 1
IQ2_VALUES = (8, 25, 43)
IQ3_XXS_VALUES = (4, 12, 20, 28, 36, 44, 52, 62)
IQ2_BASE = {16: 0, 17: 512, 22: 1024}                # IQ2_XXS, IQ2_XS, IQ2_S
IQ3_BASE = {18: 0, 21: 512}                          # IQ3_XXS, IQ3_S


def codes(fmt, values, width):
    g = H.iq_grid(fmt)
    lut = {v: i for i, v in enumerate(values)}
    return [sum(lut[int(v)] << (width * j) for j, v in enumerate(row)) for row in g]


def rom(name, depth, width, base, vals):
    words = [0] * depth
    for fmt, b in base.items():
        c = codes(fmt, vals[fmt], width // len(H.iq_grid(fmt)[0]))
        words[b:b + len(c)] = c
    digits = (width + 3) // 4
    out = [f"  type {name.lower()}_t is array (0 to {depth - 1}) of unsigned({width - 1} downto 0);\n",
           f"  constant {name} : {name.lower()}_t := (\n"]
    out.append(",\n".join(f"    x\"{w:0{digits}X}\"" if width % 4 == 0 else
                          f"    \"{w:0{width}b}\"" for w in words))
    out.append(");\n")
    return "".join(out)


iq = ("  -- IQ2 codebooks (IQ2_XXS at 0, IQ2_XS at 512, IQ2_S at 1024:\n"
      "  -- a base is one address bit, so the index is ORed in): 8 values of\n"
      "  -- 2 bits (8, 25, 43), value 0 in bits 1..0\n"
      + rom("IQ2_GRID", 2048, 16, IQ2_BASE, {f: IQ2_VALUES for f in IQ2_BASE}) +
      "  -- IQ3 codebooks (IQ3_XXS at 0, IQ3_S at 512): 4 values of 3 bits, value 0\n"
      "  -- in bits 2..0 (IQ3_XXS: 4, 12, .. 52, 62; IQ3_S: 2k + 1)\n"
      + rom("IQ3_GRID", 1024, 12, IQ3_BASE, {18: IQ3_XXS_VALUES, 21: tuple(range(1, 16, 2))}))

text = ("-- GENERATED by gen_tables.py from the SSNAIL tools (ssnail_hw.py).\n"
        "-- Do not edit: regenerate.\n"
        "library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\n\n"
        "package ssnail_tables_pkg is\n"
        f"  constant TAB_SEGMENTS : natural := {H.SEGMENTS};\n"
        f"  type tab_t is array (0 to {H.SEGMENTS - 1}) of unsigned(31 downto 0);\n\n"
        + table("SILU", H.SILU) + "\n" + table("GELU", H.GELU) + "\n" + table("EXPT", H.EXP)
        + "\n" + table("SOFTP", H.SOFTPLUS)
        + "\n" + iq + "end package;\n")

if "--check" in sys.argv:
    cur = open(OUT).read() if os.path.exists(OUT) else ""
    if cur != text:
        print("ssnail_tables_pkg.vhdl is out of date with the SSNAIL tools: run gen_tables.py")
        sys.exit(1)
    print("ssnail_tables_pkg.vhdl is up to date")
else:
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({H.SEGMENTS} segments x 4 tables; IQ2 / IQ3 codebooks)")
