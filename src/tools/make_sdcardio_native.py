#!/usr/bin/env python3
"""Generate src/vhdl/sdcardio_native.vhdl from src/vhdl/sdcardio.vhdl.

sdcardio_native is sdcardio with the old SPI-only SD controller (sdcard.vhdl)
replaced by the native 4-bit controller (sdcard_native.vhdl).  It is made by
editing a copy of sdcardio.vhdl, so that it picks up later changes to
sdcardio instead of drifting away from it: change this script, not the
generated file.  Every edit checks that the text it replaces is there exactly
once, so a change in sdcardio that collides with one stops the script.

  python3 src/tools/make_sdcardio_native.py src/vhdl/sdcardio.vhdl src/vhdl/sdcardio_native.vhdl
"""
import sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()

def rep(old, new, count=1):
    global s
    n = s.count(old)
    assert n == count, (n, old[:200])
    s = s.replace(old, new)

def cut(start, end, new, keep_end=True):
    """replace s[start_anchor : end_anchor) with new"""
    global s
    a = s.index(start); assert s.count(start) == 1, start
    b = s.index(end, a)
    s = s[:a] + new + s[b:]

