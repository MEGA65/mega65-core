#!/usr/bin/env python3
"""Generate src/vhdl/sdcardio_native.vhdl from src/vhdl/sdcardio.vhdl.

sdcardio_native is sdcardio with the old SPI-only SD controller (sdcard.vhdl)
replaced by the native 4-bit controller (sdcard_native.vhdl).  It is made by
editing a copy of sdcardio.vhdl, so that it picks up later changes to
sdcardio instead of drifting away from it: change this script, not the
generated file.  Every edit checks that the text it replaces is there exactly
once, so a change in sdcardio that collides with one stops the script.

  python3 src/tools/make_sdcardio_native.py src/vhdl/sdcardio.vhdl src/vhdl/sdcardio_native.vhdl
"""
import sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()

def rep(old, new, count=1):
    global s
    n = s.count(old)
    assert n == count, (n, old[:200])
    s = s.replace(old, new)

def cut(start, end, new, keep_end=True):
    """replace s[start_anchor : end_anchor) with new"""
    global s
    a = s.index(start); assert s.count(start) == 1, start
    b = s.index(end, a)
    s = s[:a] + new + s[b:]

# --- header, entity ---------------------------------------------------------
rep("""-- The sector buffers are a bit of a pain,""",
"""-- sdcardio_native: fork of sdcardio for the native 4-bit SD controller
-- (sdcard_native.vhdl), MEGA65/mega65-core#890.  iomapper uses it instead of
-- sdcardio when its generic sd_native is set (the mega65r6 target).
--
-- GENERATED from sdcardio.vhdl by src/tools/make_sdcardio_native.py: change
-- that script (or sdcardio.vhdl) and run it again, do not edit this file.
--
-- Differences from sdcardio:
--   * the SD card pins are the native bus of both slots (CLK, CMD, DAT3..0),
--     and the controller needs clock162 as well;
--   * sector data streams between the card and the sector buffer at up to one
--     byte per cycle (no byte handshake);
--   * multi-sector reads, like multi-sector writes:
--       $D680 <- $07  read the sector at $D681-$D684 and open a multi-sector read
--       $D680 <- $08  read the next sector of it
--       $D680 <- $09  read the next sector and end the multi-sector read
--       $D680 <- $0A  end an open multi-sector read or write (no more data)
--     ($04/$05/$06 open/continue/end a multi-sector write as before; $08/$09
--     and $05/$06 without an open transfer just read / write one sector)
--   * bus speed:
--       $D680 <- $20  probe: read sector 0 eight times with the clock setting
--                     P = $D681 bits 6..0 (SD clock = 324 MHz / P, P >= 4) and
--                     sample delay D = $D682 bits 4..0 (3.086 ns units);
--                     pass / fail counts in $D09B / $D09C
--       $D680 <- $21  use that setting from now on (as $20: $D681/$D682)
--       $D680 <- $22  back to the normal setting (40.5 MHz or 24.9 MHz)
--       $D680 <- $23  re-initialise the card in SPI mode only
--       $D680 <- $24  re-initialise the card, staying at default speed
--     (these use $D681/$D682, so set the sector number again afterwards)
--   * $D686 (read): bit 0 card ready, 1 native 4-bit bus, 2 high speed,
--     3 SDHC/SDXC, 4 transfer open and waiting, 5 multi-sector read open,
--     6 multi-sector write open, 7 low-level error
--     $D687 (read): low-level error code
--   * $D680.1 (SDCARD BUSY) is clear while an open multi-sector transfer is
--     waiting for the next $05/$06 or $08/$09.
--
-- The sector buffers are a bit of a pain,""")
